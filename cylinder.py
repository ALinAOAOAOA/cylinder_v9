import tkinter as tk
from tkinter import messagebox  # для всплывающих окон с ошибками

PI = 3.14  

def вычислить():
    try:
        # берём текст из полей и заменяем запятую на точку — на случай если пользователь введёт "3,5"
        R = float(поле_r.get().replace(',', '.'))
        H = float(поле_h.get().replace(',', '.'))
    except ValueError:
        # если в поле что-то нечисловое — выводится это
        messagebox.showerror("Ошибка", "Введите числовые значения!")
        return

    if R <= 0 or H <= 0:
        messagebox.showerror("Ошибка", "Радиус и высота должны быть больше нуля!")# отрицательный радиус или высота смысла не имеют, поэтому тоже ошибка
        return

    S_бок  = 2 * PI * R * H       # боковая поверхность
    S_осн  = 2 * PI * R ** 2      # два круглых основания
    S_полн = S_бок + S_осн        # полная поверхность = боковая + оба основания

    # обновляем текст метки с результатами, .2f — два знака после запятой
    метка_рез.config(text=f"Боковая:  {S_бок:.2f} м²\n"
                          f"Основания: {S_осн:.2f} м²\n"
                          f"Полная:   {S_полн:.2f} м²")

def очистить():
    поле_r.delete(0, tk.END)   # удаляем всё содержимое поля радиуса
    поле_h.delete(0, tk.END)   # и поля высоты
    метка_рез.config(text="")  # убираем результат с экрана

#создание главного окна
окно = tk.Tk()
окно.title("Площадь цилиндра — вариант 9")
окно.geometry("340x280")  # ширина × высота в пикселях

# заголовок и формула сверху
tk.Label(окно, text="Площадь поверхности цилиндра", font=("Arial", 13, "bold")).pack(pady=10)
tk.Label(окно, text="S = 2πRH + 2πR²   (π = 3.14)", font=("Arial", 9)).pack()

# frame нужен чтобы удобно расположить метки и поля ввода сеткой
frame = tk.Frame(окно)
frame.pack(pady=10)

# строка 0: метка "Радиус" и поле ввода рядом
tk.Label(frame, text="Радиус R (м):", font=("Arial", 11)).grid(row=0, column=0, sticky="w", pady=4)
поле_r = tk.Entry(frame, font=("Arial", 11), width=10)
поле_r.grid(row=0, column=1, pady=4)

# строка 1: то же самое для высоты
tk.Label(frame, text="Высота H (м):", font=("Arial", 11)).grid(row=1, column=0, sticky="w", pady=4)
поле_h = tk.Entry(frame, font=("Arial", 11), width=10)
поле_h.grid(row=1, column=1, pady=4)

# кнопки управления
tk.Button(окно, text="Вычислить", font=("Arial", 11), command=вычислить).pack(pady=4)
tk.Button(окно, text="Очистить",  font=("Arial", 11), command=очистить).pack()

# метка для вывода результата — изначально пустая
метка_рез = tk.Label(окно, text="", font=("Arial", 11), justify="left")
метка_рез.pack(pady=10)

окно.mainloop()  # запускаем главный цикл обработки событий
